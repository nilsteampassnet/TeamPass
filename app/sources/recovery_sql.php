/** Stream the SQL dialect written by TeamPass, respecting quoted semicolons and escapes. */
function tpRecoverySqlStatements(string $path): Generator
{
    $handle = fopen($path, 'rb');
    if ($handle === false) {
        throw new TeamPassRecoveryException('SQL_UNREADABLE');
    }
    $statement = '';
    $quote = '';
    $escape = false;
    try {
        while (($line = fgets($handle)) !== false) {
            // TeamPass does not emit client directives or executable SQL comments.
            if ($quote === '' && trim($statement) === '' && (str_starts_with(ltrim($line), '--') || trim($line) === '')) {
                continue;
            }
            $length = strlen($line);
            for ($index = 0; $index < $length; $index++) {
                $character = $line[$index];
                $statement .= $character;
                if (strlen($statement) > 268435456) {
                    throw new TeamPassRecoveryException('SQL_STATEMENT_LIMIT');
                }
                if ($quote !== '') {
                    if ($escape) {
                        $escape = false;
                    } elseif ($character === '\\') {
                        $escape = true;
                    } elseif ($character === $quote) {
                        if ($index + 1 < $length && $line[$index + 1] === $quote) {
                            $statement .= $line[++$index];
                        } else {
                            $quote = '';
                        }
                    }
                } elseif (in_array($character, ['"', "'", '`'], true)) {
                    $quote = $character;
                } elseif ($character === ';') {
                    yield trim($statement);
                    $statement = '';
                }
            }
        }
        if (!feof($handle) || $quote !== '' || trim($statement) !== '') {
            throw new TeamPassRecoveryException('SQL_TRUNCATED');
        }
    } finally {
        fclose($handle);
    }
}

/** Validate the narrow TeamPass dump dialect and return its statement type and table. */
function tpRecoverySqlStatementInfo(string $sql, string $prefix): array
{
    $table = '';
    $type = '';
    if (preg_match('/^DROP TABLE IF EXISTS `([A-Za-z0-9_]+)`;$/D', $sql, $match) === 1) {
        $type = 'drop';
        $table = $match[1];
    } elseif (preg_match('/^CREATE TABLE `([A-Za-z0-9_]+)` \(/D', $sql, $match) === 1) {
        $type = 'create';
        $table = $match[1];
        // Inspect tokens outside literals. Never allow a server-side import to reach
        // external files, another schema, arbitrary SELECTs or a remote storage engine.
        $tokens = preg_replace('/\'(?:[^\'\\\\]|\\\\.|\'\')*\'|"(?:[^"\\\\]|\\\\.|"")*"|`[^`]*`/s', ' ', $sql);
        if (!is_string($tokens) || preg_match('/\bENGINE\s*=\s*InnoDB\b/i', $tokens) !== 1
            || preg_match('/\/\*|--|#|\b(SELECT|CONNECTION|DIRECTORY|TABLESPACE|UNION|OUTFILE|DUMPFILE)\b/i', $tokens) === 1) {
            throw new TeamPassRecoveryException('SQL_DDL_UNSUPPORTED');
        }
        $referenceCount = preg_match_all('/\bREFERENCES\b/i', $tokens);
        preg_match_all('/\bREFERENCES\s+`([A-Za-z0-9_]+)`\s*\(/i', $sql, $references);
        if ($referenceCount !== count($references[1])) {
            throw new TeamPassRecoveryException('SQL_DDL_UNSUPPORTED');
        }
        foreach ($references[1] as $reference) {
            if (!str_starts_with($reference, $prefix) || strlen($reference) <= strlen($prefix)) {
                throw new TeamPassRecoveryException('SQL_SCOPE_INVALID');
            }
        }
    } elseif (preg_match('/^INSERT INTO `([A-Za-z0-9_]+)` VALUES\(/D', $sql, $match) === 1) {
        $type = 'insert';
        $table = $match[1];
        $values = substr($sql, strlen($match[0]));
        // Every value generated by tpCreateDatabaseBackup is a double-quoted string or NULL.
        if (!tpRecoverySqlLiteralValues($values)) {
            throw new TeamPassRecoveryException('SQL_VALUES_UNSUPPORTED');
        }
    }
    if ($type === '' || !str_starts_with($table, $prefix) || strlen($table) <= strlen($prefix)) {
        throw new TeamPassRecoveryException('SQL_SCOPE_INVALID');
    }
    return ['type' => $type, 'table' => $table];
}

/** Validate literal INSERT values without PCRE backtracking/JIT limits on document BLOBs. */
function tpRecoverySqlLiteralValues(string $values): bool
{
    $length = strlen($values);
    $offset = 0;
    while ($offset < $length) {
        if (substr($values, $offset, 4) === 'NULL') {
            $offset += 4;
        } elseif ($values[$offset] === '"') {
            $offset++;
            $closed = false;
            while ($offset < $length) {
                $character = $values[$offset++];
                if ($character === '\\') {
                    if ($offset >= $length) {
                        return false;
                    }
                    $offset++;
                } elseif ($character === '"') {
                    $closed = true;
                    break;
                }
            }
            if (!$closed) {
                return false;
            }
        } else {
            return false;
        }
        if ($offset === $length - 2 && substr($values, $offset) === ');') {
            return true;
        }
        if ($offset >= $length || $values[$offset++] !== ',') {
            return false;
        }
    }
    return false;
}

/** Validate the whole dump before making any database change. */
function tpRecoveryInspectSql(string $path, string $prefix): array
{
    $tables = [];
    $rows = [];
    foreach (tpRecoverySqlStatements($path) as $sql) {
        $info = tpRecoverySqlStatementInfo($sql, $prefix);
        $table = $info['table'];
        if ($info['type'] === 'create') {
            if (isset($tables[$table])) {
                throw new TeamPassRecoveryException('SQL_DUPLICATE_TABLE');
            }
            $tables[$table] = true;
            $rows[$table] = 0;
        } elseif ($info['type'] === 'insert') {
            if (!isset($tables[$table])) {
                throw new TeamPassRecoveryException('SQL_TABLE_ORDER_INVALID');
            }
            $rows[$table]++;
        } elseif (isset($tables[$table])) {
            throw new TeamPassRecoveryException('SQL_TABLE_ORDER_INVALID');
        }
    }
    foreach (['misc', 'users', 'items', 'nested_tree', 'sharekeys_items', 'user_private_keys'] as $required) {
        if (!isset($tables[$prefix . $required])) {
            throw new TeamPassRecoveryException('SQL_REQUIRED_TABLE_MISSING');
        }
    }
    return ['tables' => array_keys($tables), 'rows' => $rows];
}
