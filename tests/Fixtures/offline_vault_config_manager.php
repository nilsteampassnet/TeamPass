// Settings source of OfflineVaultController::settings(), without a database.
// Load in a separate process only: it replaces the real autoloaded class.

namespace TeampassClasses\ConfigManager;

final class ConfigManager
{
    /** Settings the next getAllSettings() call returns. */
    public static array $settings = [];

    /**
     * Return the configured settings.
     *
     * @return array
     */
    public function getAllSettings(): array
    {
        return self::$settings;
    }
}
